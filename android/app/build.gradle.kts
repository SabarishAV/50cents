// Flutter copies the assembled release APK to
// build/app/outputs/flutter-apk/app-release.apk. Create a consistently named
// release artifact after every release build.
val copyReleaseApk = tasks.register("copyReleaseApk") {
    doLast {
        val outputDir = layout.buildDirectory.dir("outputs/flutter-apk").get().asFile
        val source = File(outputDir, "app-release.apk")
        val target = File(outputDir, "50cents.apk")
        if (source.exists()) {
            source.copyTo(target, overwrite = true)
        } else {
            logger.warn("Release APK not found at $source; skipping 50cents.apk copy")
        }
    }
}

tasks.configureEach {
    if (name == "assembleRelease") {
        finalizedBy(copyReleaseApk)
    }
}

